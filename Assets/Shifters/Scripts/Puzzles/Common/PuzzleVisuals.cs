using System.Globalization;
using TMPro;
using UnityEngine;

namespace Shifters
{
    /// <summary>Building blocks for SHIFTERS' puzzle visual language (lamps, TMP labels, floating displays,
    /// hazard stripes, chevrons, cylinders). Everything goes through cached meshes + Kit materials, so it works in
    /// edit mode (scene builder) and at runtime.</summary>
    public static class PuzzleVisuals
    {
        static readonly CultureInfo Inv = CultureInfo.InvariantCulture;

        // ------------------------------------------------------------------ fonts
        static TMP_FontAsset _font;
        static bool _fontSearched;

        [RuntimeInitializeOnLoadMethod(RuntimeInitializeLoadType.SubsystemRegistration)]
        static void ResetStatics() { _font = null; _fontSearched = false; }

        /// <summary>Preferred label font: a condensed/black font generated by the UI agent into Resources/Fonts, else TMP default.</summary>
        public static TMP_FontAsset Font
        {
            get
            {
                if (_fontSearched) return _font;
                _fontSearched = true;
                var all = Resources.LoadAll<TMP_FontAsset>("Fonts");
                string[] prefs = { "Condensed", "Black", "Bungee", "SemiBold" };
                foreach (var p in prefs)
                    foreach (var f in all)
                        if (f != null && f.name.IndexOf(p, System.StringComparison.OrdinalIgnoreCase) >= 0) { _font = f; return _font; }
                _font = all.Length > 0 ? all[0] : null;
                return _font;
            }
        }

        // ------------------------------------------------------------------ meshes
        public static Mesh Cylinder(float radius, float height, int segments = 16)
            => ProcMesh.Cached(string.Format(Inv, "pz_cyl_{0:0.###}x{1:0.###}_{2}", radius, height, segments), () => ProcMesh.Cylinder(radius, height, segments, false));

        public static Mesh Sphere(float radius)
            => ProcMesh.Cached(string.Format(Inv, "pz_sph_{0:0.###}", radius), () => ProcMesh.Sphere(radius, 12, 8, true));

        public static MeshRenderer Box(Transform parent, string name, Vector3 center, Vector3 size, MatKey mat, float bevel = 0.03f, Quaternion? rot = null, bool shadows = true)
            => Kit.BoxVisual(parent, name, center, size, mat, bevel, rot, shadows);

        public static MeshRenderer Box(Transform parent, string name, Vector3 center, Vector3 size, Material mat, float bevel = 0.03f, Quaternion? rot = null, bool shadows = true)
        {
            var go = Kit.Make(name, parent, center, rot ?? Quaternion.identity);
            return ProcMesh.AddRenderer(go, ProcMesh.CachedBox(size, bevel), mat, shadows);
        }

        public static MeshRenderer Cyl(Transform parent, string name, Vector3 center, float radius, float height, MatKey mat, Quaternion? rot = null, int segments = 16, bool shadows = true)
        {
            var go = Kit.Make(name, parent, center, rot ?? Quaternion.identity);
            return ProcMesh.AddRenderer(go, Cylinder(radius, height, segments), Kit.Mat(mat), shadows);
        }

        // ------------------------------------------------------------------ lamps
        /// <summary>Indicator lamp (dark bezel + glowing bulb). Faces local +Z of 'rot' (bulb protrudes along +Z).</summary>
        public static PuzzleLamp Lamp(Transform parent, string name, Vector3 localPos, Quaternion rot, float size = 0.16f, PuzzleLampColor initial = PuzzleLampColor.Red)
        {
            var root = Kit.Make(name, parent, localPos, rot);
            Box(root.transform, "Bezel", new Vector3(0f, 0f, -0.01f), new Vector3(size * 1.35f, size * 1.35f, 0.05f), MatKey.MetalDark, 0.015f, null, false);
            var bulb = Box(root.transform, "Bulb", new Vector3(0f, 0f, 0.03f), new Vector3(size, size, size * 0.45f), PuzzleLamp.DefaultMaterial(initial), size * 0.2f, null, false);
            var lamp = root.AddComponent<PuzzleLamp>();
            lamp.Renderers = new Renderer[] { bulb };
            lamp.Palette = PuzzleLamp.DefaultPalette();
            lamp.Set(initial);
            return lamp;
        }

        /// <summary>A lamp made of an arbitrary set of renderers (light strips, cable cores).</summary>
        public static PuzzleLamp LampFrom(GameObject host, PuzzleLampColor initial, params Renderer[] renderers)
        {
            var lamp = host.AddComponent<PuzzleLamp>();
            lamp.Renderers = renderers;
            lamp.Palette = PuzzleLamp.DefaultPalette();
            lamp.Set(initial);
            return lamp;
        }

        // ------------------------------------------------------------------ text
        /// <summary>TextMeshPro 3D label. The readable face looks along local -Z of its transform (use Facing()).</summary>
        public static TextMeshPro Text(Transform parent, string name, Vector3 localPos, Quaternion localRot, string text, float fontSize, Color color, float width = 3f, float height = 1f)
        {
            var go = Kit.Make(name, parent, localPos, localRot);
            var t = go.AddComponent<TextMeshPro>();
            var f = Font;
            if (f != null) t.font = f;
            t.text = text;
            t.fontSize = fontSize;
            t.color = color;
            t.alignment = TextAlignmentOptions.Center;
            t.textWrappingMode = TextWrappingModes.NoWrap;
            t.fontStyle = FontStyles.Bold;
            t.rectTransform.sizeDelta = new Vector2(width, height);
            var r = go.GetComponent<MeshRenderer>();
            if (r != null) { r.shadowCastingMode = UnityEngine.Rendering.ShadowCastingMode.Off; r.receiveShadows = false; }
            return t;
        }

        /// <summary>Rotation for a label whose readable side faces 'outward' (local direction).</summary>
        public static Quaternion Facing(Vector3 outward)
        {
            var up = Mathf.Abs(Vector3.Dot(outward.normalized, Vector3.up)) > 0.95f ? Vector3.forward : Vector3.up;
            return Quaternion.LookRotation(-outward, up);
        }

        /// <summary>Floating billboard display: dark panel + teal underline, returns the root (texts are children you add).</summary>
        public static Transform Display(Transform parent, string name, Vector3 localPos, float width, float height, bool billboard = true)
        {
            var root = Kit.Make(name, parent, localPos);
            if (billboard) root.AddComponent<PuzzleBillboard>();
            Box(root.transform, "Panel", new Vector3(0f, 0f, 0.05f), new Vector3(width, height, 0.06f), MatKey.Black, 0.03f, null, false);
            Box(root.transform, "Underline", new Vector3(0f, -height * 0.5f, 0.05f), new Vector3(width + 0.04f, 0.05f, 0.08f), MatKey.PuzzleBody, 0.015f, null, false);
            return root.transform;
        }

        /// <summary>Display with a big requirement line and a smaller live line.</summary>
        public static Transform TwoLineDisplay(Transform parent, Vector3 localPos, float width, string big, string small, out TextMeshPro bigText, out TextMeshPro smallText)
        {
            var d = Display(parent, "Display", localPos, width, 0.78f);
            bigText = Text(d, "Requirement", new Vector3(0f, 0.14f, 0f), Quaternion.identity, big, 3.4f, UIColors.AccentYellow, width, 0.45f);
            smallText = Text(d, "Live", new Vector3(0f, -0.2f, 0f), Quaternion.identity, small, 2.4f, UIColors.Text, width, 0.35f);
            return d;
        }

        // ------------------------------------------------------------------ stripes & chevrons
        /// <summary>Hazard-striped bar: black core with yellow bands along local axis (0=x,1=y,2=z).</summary>
        public static void StripedBox(Transform parent, string name, Vector3 center, Vector3 size, int axis = 0, float band = 0.35f, bool shadows = true)
        {
            var root = Kit.Make(name, parent, center);
            Box(root.transform, "Black", Vector3.zero, size, MatKey.HazardBlack, 0.02f, null, shadows);
            float len = size[axis];
            int count = Mathf.Max(1, Mathf.FloorToInt(len / (band * 2f)));
            var bandSize = size + new Vector3(0.02f, 0.02f, 0.02f);
            bandSize[axis] = band;
            string key = string.Format(Inv, "pz_stripes_{0:0.##}x{1:0.##}x{2:0.##}_{3}_{4:0.##}", size.x, size.y, size.z, axis, band);
            var mesh = ProcMesh.Cached(key, () =>
            {
                var b = new ProcMesh.Builder();
                float start = -count * band + band * 0.5f;
                for (int i = 0; i < count; i++)
                {
                    var c = Vector3.zero;
                    c[axis] = start + i * band * 2f;
                    b.AddBox(c, bandSize, Quaternion.identity, Color.white, 0.01f);
                }
                return b.ToMesh(key);
            });
            ProcMesh.Part("Yellow", root.transform, mesh, Kit.Mat(MatKey.HazardYellow), Vector3.zero, null, null, shadows);
        }

        /// <summary>Vertical chevron column (arrows pointing local +Y) drawn on a plane facing local +Z.</summary>
        public static Mesh ChevronColumnMesh(float width, float height, int count, float thickness)
        {
            string key = string.Format(Inv, "pz_chev_col_{0:0.##}x{1:0.##}_{2}_{3:0.###}", width, height, count, thickness);
            return ProcMesh.Cached(key, () =>
            {
                var b = new ProcMesh.Builder();
                float arm = width * 0.42f;
                float step = height / count;
                for (int i = 0; i < count; i++)
                {
                    float y = -height * 0.5f + step * (i + 0.5f);
                    var l = new Vector3(-arm * 0.5f, y, 0f);
                    var r = new Vector3(arm * 0.5f, y, 0f);
                    var sz = new Vector3(arm * 1.25f, step * 0.22f, thickness);
                    b.AddBox(l, sz, Quaternion.Euler(0f, 0f, 30f), Color.white, 0.01f);
                    b.AddBox(r, sz, Quaternion.Euler(0f, 0f, -30f), Color.white, 0.01f);
                }
                return b.ToMesh(key);
            });
        }

        /// <summary>One flat floor chevron pointing local +Z (for routes and conveyors).</summary>
        public static Mesh FloorChevronMesh(float size)
        {
            string key = string.Format(Inv, "pz_chev_floor_{0:0.##}", size);
            return ProcMesh.Cached(key, () =>
            {
                var b = new ProcMesh.Builder();
                var sz = new Vector3(size * 0.75f, 0.02f, size * 0.18f);
                b.AddBox(new Vector3(-size * 0.25f, 0f, 0f), sz, Quaternion.Euler(0f, -40f, 0f), Color.white, 0.005f);
                b.AddBox(new Vector3(size * 0.25f, 0f, 0f), sz, Quaternion.Euler(0f, 40f, 0f), Color.white, 0.005f);
                return b.ToMesh(key);
            });
        }

        /// <summary>L-shaped corner bracket on the floor (zone markers).</summary>
        public static void FloorCorners(Transform parent, Vector3 center, Vector2 size, MatKey mat)
        {
            float a = Mathf.Min(0.6f, Mathf.Min(size.x, size.y) * 0.25f);
            for (int sx = -1; sx <= 1; sx += 2)
                for (int sz = -1; sz <= 1; sz += 2)
                {
                    var corner = center + new Vector3(sx * size.x * 0.5f, 0.01f, sz * size.y * 0.5f);
                    Box(parent, "CornerX", corner + new Vector3(-sx * a * 0.5f, 0f, 0f), new Vector3(a, 0.02f, 0.08f), mat, 0.005f, null, false);
                    Box(parent, "CornerZ", corner + new Vector3(0f, 0f, -sz * a * 0.5f), new Vector3(0.08f, 0.02f, a), mat, 0.005f, null, false);
                }
        }
    }
}
